nums=[5,10,1,60,25,3]
print("Список из чисел:", nums)
print("Длина списка равна:", len(nums))
print("первый элемент списка:", nums[0])
print("Последний элемент списка:", nums[-1])
print("Наибольшее значение в списке:", max(nums))
print("Наименьшее значение в списке:", min(nums))
print("Сумма элементов списка равна:", sum(nums))
print("Список в обатном порядке:", list(reversed(nums)))
print("Сортировка элементов списка по возрастанию:", sorted(nums))
print("Сортировка элементов списка по убыванию:", sorted(nums, reverse=True))
print("Исходный список:", nums)